const translations = {
  de, fr, es, pt, it
};

for (const [lang, patch] of Object.entries(translations)) {
  const filePath = path.join(LANG_DIR, `${lang}.json`);
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  if (!data.opt) {
    console.log(`[${lang}] No opt section found – skipping`);
    continue;
  }

  let updated = 0;
  let skipped = 0;

  for (const [key, translation] of Object.entries(patch)) {
    // Only overwrite if current value is identical to the English key
    // (meaning it was never translated)
    if (data.opt[key] === enOpt[key]) {
      data.opt[key] = translation;
      updated++;
    } else {
      skipped++;
    }
  }

  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log(`[${lang}] ${updated} updated, ${skipped} already translated`);
}

