function patchFile(filename, translations) {
  const filePath = path.join(LANG_DIR, filename);
  console.log(`Reading ${filePath} ...`);
  const raw = fs.readFileSync(filePath, 'utf8');
  const data = JSON.parse(raw);

  if (!data.opt) {
    console.error(`  ERROR: no "opt" section found in ${filename}`);
    process.exit(1);
  }

  let patched = 0;
  let already = 0;
  for (const [key, value] of Object.entries(translations)) {
    if (data.opt[key] === undefined) {
      // Key doesn't exist yet in the file – add it
      data.opt[key] = value;
      patched++;
    } else if (data.opt[key] === key || data.opt[key] === value) {
      // Still English fallback (value === key) OR already same translation
      if (data.opt[key] === key) {
        data.opt[key] = value;
        patched++;
      } else {
        already++;
      }
    } else {
      // Already has a non-English translation that differs from ours – keep existing
      already++;
    }
  }

  const output = JSON.stringify(data, null, 2) + '\n';
  fs.writeFileSync(filePath, output, 'utf8');
  console.log(`  Patched ${patched} keys, ${already} already translated. Written to ${filePath}`);
}

