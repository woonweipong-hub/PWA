function deepSet(obj, dottedKey, value) {
  const parts = dottedKey.split(".");
  let cur = obj;
  for (let i = 0; i < parts.length - 1; i++) {
    if (!cur[parts[i]]) cur[parts[i]] = {};
    cur = cur[parts[i]];
  }
  cur[parts[parts.length - 1]] = value;
}

const langs = fs.readdirSync(LANG_DIR).filter(f => f.endsWith(".json"));

for (const file of langs) {
  const code = file.replace(".json", "");
  const filePath = path.join(LANG_DIR, file);
  const data = JSON.parse(fs.readFileSync(filePath, "utf8"));

  // 1. Add "opt" section
  if (code === "en") {
    data.opt = EN_OPT;
  } else {
    // Merge: use translated value if available, fallback to English
    const langOpt = TRANSLATIONS[code] || {};
    const merged = {};
    for (const key of Object.keys(EN_OPT)) {
      merged[key] = langOpt[key] || key; // fallback to English value
    }
    data.opt = merged;
  }

  // 2. Add extra UI keys
  const extra = EXTRA_KEYS[code] || EXTRA_KEYS.en;
  for (const [dottedKey, value] of Object.entries(extra)) {
    deepSet(data, dottedKey, value);
  }

  // 3. Write back
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + "\n", "utf8");
  console.log(`✓ ${file} — opt keys: ${Object.keys(data.opt).length}`);
}

