// ---------------------------------------------------------------------------
// Map of language code -> translations
// ---------------------------------------------------------------------------
const TRANSLATIONS = { hi, ta, bn, th, vi, id };

// ---------------------------------------------------------------------------
// Read the English file to get the canonical keys
// ---------------------------------------------------------------------------
const enPath = path.join(LANG_DIR, 'en.json');
const enData = JSON.parse(fs.readFileSync(enPath, 'utf8'));
const enOpt = enData.opt || {};

// ---------------------------------------------------------------------------
// Patch each language file
// ---------------------------------------------------------------------------
let totalPatched = 0;

for (const [lang, translations] of Object.entries(TRANSLATIONS)) {
  const filePath = path.join(LANG_DIR, `${lang}.json`);

  if (!fs.existsSync(filePath)) {
    console.log(`  SKIP  ${lang}.json — file not found`);
    continue;
  }

  const raw = fs.readFileSync(filePath, 'utf8');
  const data = JSON.parse(raw);

  if (!data.opt) {
    data.opt = {};
  }

  let patchedCount = 0;

  for (const [key, localValue] of Object.entries(translations)) {
    const currentValue = data.opt[key];
    const englishValue = enOpt[key]; // the canonical English value for this key

    // Only patch if:
    //  (a) key doesn't exist yet in the file, OR
    //  (b) current value is identical to the English key string (untranslated)
    //      — we compare against BOTH the key itself AND the english opt value
    if (
      currentValue === undefined ||
      currentValue === key ||
      (englishValue !== undefined && currentValue === englishValue)
    ) {
      data.opt[key] = localValue;
      patchedCount++;
    }
  }

  // Write back with 2-space indent + trailing newline (matching original format)
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2) + '\n', 'utf8');

  console.log(`  DONE  ${lang}.json — ${patchedCount} values patched`);
  totalPatched += patchedCount;
}

console.log(`\nTotal: ${totalPatched} translations patched across ${Object.keys(TRANSLATIONS).length} files.`);
